"""Mod files whose full path is longer than Windows' 260-character limit (the Nexus report of 2026-10-21: the window
stayed empty with "[WinError 3] The system cannot find the path specified" on a Dragons Use Thu'um animation file).

ModOrganizer.exe 2.5.2 has no longPathAware entry in its manifest, so the Python it hosts gets MAX_PATH-limited
Win32 calls whatever the LongPathsEnabled registry value says. python.exe IS longPathAware, so a plain offline run
never shows the failure. This test clears the process's PEB IsLongPathAwareProcess bit (bit 7 of PEB+3) to run the
plugin the way MO2 runs it, and proves the emulation first (a long path must fail with WinError 3 after the flip).

The scratch instance is built under --root (default: mm-longpath-scratch in the temp folder) and kept, so it can
also be opened by a scratch MO2. Nothing outside --root is written.

    python tools\\test_long_paths.py [--root DIR] [--no-emulate]      exit 0 = every check passed
"""
import ctypes, ctypes.wintypes as wt, importlib.util, os, shutil, sys, tempfile, traceback, types

args = sys.argv[1:]
ROOT = args[args.index("--root") + 1] if "--root" in args else os.path.join(tempfile.gettempdir(), "mm-longpath-scratch")
EMULATE = "--no-emulate" not in args

os.environ["QT_QPA_PLATFORM"] = "offscreen"
stub = types.ModuleType("mobase")
stub.__getattr__ = lambda n: type(n, (object,), {"__init__": lambda self, *a, **k: None})
sys.modules["mobase"] = stub
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

bad = 0


def ok(cond, what):
    global bad
    print(("PASS " if cond else "FAIL ") + what)
    bad += 0 if cond else 1


def X(p):
    return "\\\\?\\" + os.path.abspath(p)       # only the test's own set-up writes through the prefix


# ---- the scratch instance (written before the emulation, through \\?\ so it works on any machine) -------------
INST = os.path.join(ROOT, "Skyrim Special Edition - A Portable Instance Folder With A Deliberately Long Name For Testing")
MODS = os.path.join(INST, "mods")
PROF = os.path.join(INST, "profiles", "Default")
LONG_MOD = "Dragons Use Thu'um - Dragon Shout and Breath Attack Overhaul"
DEEP_MOD = ("Animation Pack With An Extremely Long Folder Name - " + "Version Two Point Zero - Full Release - " * 3).rstrip(" -")
BREATH = r"meshes\actors\dragon\animations\breathattacks\ground_exhalefirebreath.hkx"
DEEPER = r"meshes\actors\character\animations\combat\attacks\heavy\variants\second set\final pass\mt_heavyattack_long.hkx"
if os.path.isdir(X(ROOT)):
    shutil.rmtree(X(ROOT))


def put(rel, data=b"x" * 64):
    p = os.path.join(INST, rel)
    os.makedirs(X(os.path.dirname(p)), exist_ok=True)
    open(X(p), "wb").write(data if isinstance(data, bytes) else data.encode("utf-8"))
    return p


for name, modid, ver, arc in ((LONG_MOD, 12345, "1.2.0", "Dragons Use Thuum-12345-1-2.7z"),
                              (DEEP_MOD, 22222, "2.0.0", "Animation Pack-22222-2-0.7z"),
                              ("SkyUI", 12604, "5.2.0", "SkyUI_5_2_SE-12604-5-2SE.7z")):
    put(os.path.join("mods", name, "meta.ini"), f"[General]\nmodid={modid}\nversion={ver}\ninstallationFile={arc}\n")
put(os.path.join("mods", LONG_MOD, "DragonsUseThuum.esp"), b"TES4" + b"\0" * 20)
breath = put(os.path.join("mods", LONG_MOD, BREATH))
deeper = put(os.path.join("mods", DEEP_MOD, DEEPER))
put(os.path.join("mods", DEEP_MOD, "textures", "short.dds"))
put(os.path.join("mods", "SkyUI", "interface", "skyui", "config.txt"))
os.makedirs(X(PROF), exist_ok=True)
open(X(os.path.join(INST, "ModOrganizer.ini")), "w").write("[General]\ngameName=Skyrim Special Edition\n\n[Settings]\n")
open(X(os.path.join(PROF, "modlist.txt")), "w", newline="\r\n").write(
    "# This file was automatically generated by Mod Organizer.\n+" + LONG_MOD + "\n+" + DEEP_MOD + "\n+SkyUI\n")
open(X(os.path.join(PROF, "plugins.txt")), "w", newline="\r\n").write(
    "# This file was automatically generated by Mod Organizer.\n*DragonsUseThuum.esp\n")
print(f"instance path {len(INST)} chars; mod folder {len(os.path.join(MODS, LONG_MOD))}; "
      f"breath file {len(breath)}; deepest folder {len(os.path.dirname(deeper))}; deepest file {len(deeper)}")
ok(len(breath) > 260 and len(os.path.dirname(breath)) < 258, "the breath file is over 260 characters in a folder under it")
ok(len(os.path.dirname(deeper)) > 260, "the deepest folder is itself over 260 characters")


# ---- run the plugin the way ModOrganizer.exe runs it ---------------------------------------------------------
def set_long_path_aware(on):
    class PBI(ctypes.Structure):
        _fields_ = [("ExitStatus", ctypes.c_void_p), ("PebBaseAddress", ctypes.c_void_p), ("Affinity", ctypes.c_void_p),
                    ("Priority", ctypes.c_void_p), ("Pid", ctypes.c_void_p), ("Parent", ctypes.c_void_p)]
    pbi = PBI()
    nt = ctypes.WinDLL("ntdll")
    nt.NtQueryInformationProcess(wt.HANDLE(-1), 0, ctypes.byref(pbi), ctypes.sizeof(pbi), None)
    flags = ctypes.c_ubyte.from_address(pbi.PebBaseAddress + 3)
    flags.value = (flags.value | 0x80) if on else (flags.value & 0x7F)


if EMULATE:
    set_long_path_aware(False)
    try:
        os.path.getsize(breath)
        ok(False, "emulation: a 260+ path still opens, so this run would not behave like MO2")
    except OSError as e:
        ok(getattr(e, "winerror", 0) == 3, f"emulation: a 260+ path fails the way it does inside MO2: {e!r}")

spec = importlib.util.spec_from_file_location("mm", os.path.join(HERE, "MO2ModlistManager.py"))
mm = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mm)
from PyQt6.QtWidgets import QApplication

app = QApplication.instance() or QApplication([])
app.setProperty("dataPath", INST.replace("\\", "/"))


class Org:
    def basePath(self): return INST.replace("\\", "/")
    def modsPath(self): return MODS.replace("\\", "/")
    def profilePath(self): return PROF.replace("\\", "/")
    def profileName(self): return "Default"
    def refresh(self, save=True): pass
    def managedGame(self): raise RuntimeError("no game in the test")
    def pluginSetting(self, plugin, key): return None
    def setPluginSetting(self, *a): pass
    def pluginDataPath(self): return os.path.join(ROOT, "plugin-data")


p = mm.MO2ModlistManager()
p._organizer = Org()
res = None
try:
    res = p.compute()
    ok(True, "compute() finished")
except Exception:  # noqa: BLE001
    ok(False, "compute() raised:\n" + traceback.format_exc())
if res:
    by = {m.name: m for m in res["mods"]}
    ok(BREATH.replace("\\", "/").lower() in by[LONG_MOD].files, f"the 260+ breath file is in the mod's file evidence")
    ok(DEEPER.replace("\\", "/").lower() in by[DEEP_MOD].files, "a file in a 260+ folder is in the mod's file evidence")
    ok("textures/short.dds" in by[DEEP_MOD].files, "the deep mod's short file is still read")
    ok("missing" not in by[DEEP_MOD].flags, "a mod folder with 260+ paths inside is not reported missing")
    ok(not res.get("read_errors"), f"no mod reported unreadable: {res.get('read_errors')}")

# the dialog: a failure must never leave it empty
if hasattr(mm, "RulerDialog"):
    dlg = mm.RulerDialog(p)
    ok(dlg.t_place.rowCount() >= 3, f"the window lists the mods after a normal open ({dlg.t_place.rowCount()} rows)")
    real = p.compute
    p.compute = lambda *a, **k: (_ for _ in ()).throw(FileNotFoundError(3, "The system cannot find the path specified", breath))
    dlg2 = mm.RulerDialog(p)                 # a fresh window whose very first read fails
    rows = dlg2.t_place.rowCount()
    ok(rows == 3 and "could not be made" in dlg2.summary.text(),
       f"a window whose read fails still lists the mods as they are ({rows} rows) with the reason: {dlg2.summary.text()[:120]!r}")
    p.compute = real
    if res and res.get("read_errors") is not None:
        res["read_errors"] = [(LONG_MOD, "[WinError 3] test")]
        p.compute = lambda *a, **k: res
        dlg3 = mm.RulerDialog(p)
        ok(dlg3.t_place.rowCount() >= 3 and "could not be read in full" in dlg3.status.text(),
           f"an unreadable folder is named in the window, and the plan still shows: {dlg3.status.text()[:120]!r}")
        p.compute = real
print("ALL PASS" if not bad else f"{bad} FAILED")
sys.exit(1 if bad else 0)
