"""Undo pressed soon after Apply raised MO2's own Error window "failed to write mod list: invalid mod index: 92"
(scratch MO2, 2026-11-20: Undo half a second after Apply; the same Undo seven seconds after Apply raised nothing).

MO2 saves modlist.txt LATE: every refresh ends by queueing a save, written a moment afterwards. And MO2's refresh
(v2.5.2 organizercore.cpp OrganizerCore::refresh, profile.cpp Profile::refreshModStatus / doWriteModlist):
    1 with saveChanges: writes a queued save now
    2 re-reads the mods folder (the mod collection, indexed by position)
    3 refreshModStatus - whose FIRST line writes a queued save, from the order MO2 held BEFORE step 2
    4 reads modlist.txt into that order
    5 starts reading the folders on another thread; when that finishes (back in the event loop) a save is QUEUED
So a change that lands while a save is queued makes step 3 write MO2's older order against the new folder: with fewer
folders an index is out of range (the Error window, the write abandoned); with as many or more, the older order goes
over the file just written, silently.

FakeMO2 below is that order and nothing else. The test shows the old call sequence produces both faults in it, and
that the plugin's restore() and apply() produce neither. No MO2, no instance: restore_backup() and apply() are
replaced by stand-ins that change the fake's folder and file the way the real ones do.

    python tools\\test_refresh_order.py      exit 0 = every check passed
"""
import importlib.util, os, shutil, sys, tempfile, types

os.environ["QT_QPA_PLATFORM"] = "offscreen"
stub = types.ModuleType("mobase")
stub.__getattr__ = lambda n: type(n, (object,), {"__init__": lambda self, *a, **k: None})
sys.modules["mobase"] = stub
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location("MO2ModlistManager", os.path.join(HERE, "MO2ModlistManager.py"))
MM = importlib.util.module_from_spec(spec)
spec.loader.exec_module(MM)

bad = 0


def ok(cond, what, detail=""):
    global bad
    print(("PASS " if cond else "FAIL ") + what)
    if not cond:
        bad += 1
        if detail != "":
            print("     ", detail)


HEADER = "# This file was automatically generated by Mod Organizer.\r\n"


class FakeMO2:
    """mobase.IOrganizer as far as the plugin's apply() / restore() use it, with MO2's refresh order."""

    def __init__(self, root, mods):
        self.mods_dir = os.path.join(root, "mods")
        self.prof = os.path.join(root, "profiles", "Default")
        os.makedirs(self.prof)
        for m in mods:
            os.makedirs(os.path.join(self.mods_dir, m))
        self.write_file(list(mods))
        self.collection, self.order, self.queued = [], [], False     # order: indexes into collection, top first
        self.background = False
        self.errors, self.calls = [], []
        self.refresh(False)
        self.settle()

    # -- the file
    def path(self):
        return os.path.join(self.prof, "modlist.txt")

    def write_file(self, names):
        with open(self.path(), "wb") as fh:
            fh.write((HEADER + "".join("+" + n + "\r\n" for n in names)).encode("utf-8"))

    def read_file(self):
        with open(self.path(), "rb") as fh:
            lines = fh.read().decode("utf-8").replace("\r\n", "\n").split("\n")
        return [ln[1:] for ln in lines if ln[:1] in ("+", "-")]

    # -- MO2's side
    def _save_queued(self):
        """Profile::doWriteModlist, run only when a save is queued."""
        if not self.queued:
            return
        self.queued = False
        names = []
        for idx in self.order:
            if idx >= len(self.collection):                      # ModInfo::getByIndex
                self.errors.append("failed to write mod list: invalid mod index: %d" % idx)
                return                                           # the SafeWriteFile is never committed
            names.append(self.collection[idx])
        self.write_file(names)

    def refresh(self, save):
        self.calls.append(("refresh", save))
        if save:
            self._save_queued()                                  # 1
        self.collection = sorted(os.listdir(self.mods_dir))      # 2
        self._save_queued()                                      # 3  refreshModStatus's first line
        self.order = [self.collection.index(n) for n in self.read_file() if n in self.collection]      # 4
        if not self.background:                                  # refreshDirectoryStructure: not while one is running
            self._save_queued()                                  #   (it writes a queued save too - consistent by now)
            self.background = True                               #   and reads the folders on another thread

    def tick(self):
        """MO2's event loop runs (a dialog closes, a button is pressed): the background read has finished, and
        refreshESPList QUEUES a save of the mod list. It is written a moment later - not yet."""
        if self.background:
            self.background = False
            self.queued = True

    def settle(self):
        """Seconds pass: the background read finishes and the queued save is written."""
        self.tick()
        self._save_queued()

    # -- what the plugin asks for
    def profilePath(self):
        return self.prof

    def profileName(self):
        return "Default"

    def pluginList(self):
        raise RuntimeError("no plugin list in this test")       # the plugin logs and carries on


def do_apply(mo2, new_order, new_separators):
    """What the module's apply() leaves on disk: the new separator folders, modlist.txt re-sorted."""
    for s in new_separators:
        os.makedirs(os.path.join(mo2.mods_dir, s))
    mo2.write_file(new_order)


def do_restore(mo2, old_order, separators):
    """What restore_backup() leaves on disk: the Apply's separators set aside, modlist.txt as the backup holds it."""
    for s in separators:
        shutil.rmtree(os.path.join(mo2.mods_dir, s))
    mo2.write_file(old_order)


def plugin_for(mo2, log):
    p = MM.MO2ModlistManager.__new__(MM.MO2ModlistManager)
    p._organizer = mo2
    p._log = log.append
    p._instance = lambda: None
    p._cache_dir = lambda: mo2.prof
    p._verify_groups_later = lambda result: None
    return p


T = tempfile.mkdtemp(prefix="mm-refresh-order-")
MODS = ["Alpha", "Bravo", "Charlie", "Delta"]
SEPS = ["Armour_separator", "Weapons_separator"]
SORTED = ["Armour_separator", "Bravo", "Alpha", "Weapons_separator", "Delta", "Charlie"]
RESORT = ["Delta", "Charlie", "Bravo", "Alpha"]

try:
    # ---- 1  the old sequence: restore_backup, then refresh(False) - while Apply's save is still queued ------------
    m = FakeMO2(os.path.join(T, "a"), MODS)
    do_apply(m, SORTED, SEPS)
    m.refresh(False)                               # Apply's own refresh
    m.tick()                                       # back in the event loop: the background read ends, a save is queued
    ok(m.read_file() == SORTED and m.queued, "after Apply: the file is the plan's, and MO2 has a save queued")
    do_restore(m, MODS, SEPS)                      # Undo at once
    m.refresh(False)
    ok(m.errors == ["failed to write mod list: invalid mod index: 4"] or
       (len(m.errors) == 1 and m.errors[0].startswith("failed to write mod list: invalid mod index:")),
       "OLD sequence, Undo at once: MO2 reports 'failed to write mod list: invalid mod index' (the Error window)", m.errors)
    ok(m.read_file() == MODS, "... and the restored file survives only because that write was abandoned", m.read_file())

    m = FakeMO2(os.path.join(T, "b"), MODS)
    do_apply(m, SORTED, SEPS)
    m.refresh(False)
    m.settle()                                     # seven seconds pass: the queued save is written
    do_restore(m, MODS, SEPS)
    m.refresh(False)
    ok(m.errors == [] and m.read_file() == MODS, "OLD sequence, Undo later: nothing reported (why it was not seen before)", m.errors)

    m = FakeMO2(os.path.join(T, "c"), MODS)
    do_apply(m, RESORT, [])                        # an Apply that only re-sorts: no folder comes or goes
    m.refresh(False)
    m.tick()
    do_restore(m, MODS, [])
    m.refresh(False)
    ok(m.errors == [] and m.read_file() == RESORT,
       "OLD sequence, no folder removed: MO2 SILENTLY puts its older order over the restored file", (m.errors, m.read_file()))

    # ---- 2  the plugin's restore(): the queued save is written first, the result is checked ------------------------
    for label, plan, seps in (("separators removed", SORTED, SEPS), ("order only", RESORT, [])):
        m = FakeMO2(os.path.join(T, "d-" + label.replace(" ", "")), MODS)
        log = []
        p = plugin_for(m, log)
        do_apply(m, plan, seps)
        m.refresh(False)
        m.tick()                                   # Undo is pressed: a save is queued
        ok(m.queued, f"restore ({label}): a save is queued when Undo is pressed")
        MM.restore_backup = lambda *a, m=m, seps=seps, **k: (do_restore(m, MODS, seps), ("safety", [], [], []))[1]
        m.calls.clear()
        out = p.restore("backup")
        ok(m.errors == [], f"restore() at once ({label}): MO2 reports nothing", m.errors)
        ok(m.read_file() == MODS, f"restore() at once ({label}): modlist.txt is the backup's", m.read_file())
        ok(m.calls[0] == ("refresh", True) and ("refresh", True) not in m.calls[1:] and m.calls[-1] == ("refresh", False),
           f"restore() ({label}): one saving refresh BEFORE the files change, none after", m.calls)
        ok(out[0] == "safety", "restore() hands back what restore_backup returned")
        m.settle()
        ok(m.errors == [] and m.read_file() == MODS, f"... and it stays so once MO2's later save is written ({label})", m.read_file())

    # ---- 3  a restore that fails and rolls back: nothing changed, nothing refreshed twice -------------------------
    m = FakeMO2(os.path.join(T, "e"), MODS)
    p = plugin_for(m, [])

    def failing(*a, **k):
        raise MM.RestoreFailed("nothing was changed", rolled_back=True) if "rolled_back" in MM.RestoreFailed.__init__.__code__.co_varnames \
            else MM.RestoreFailed("nothing was changed")
    MM.restore_backup = failing
    try:
        p.restore("backup")
        ok(False, "a failed restore raises")
    except MM.RestoreFailed:
        ok(m.read_file() == MODS and m.errors == [], "a failed, rolled-back restore leaves the file and MO2 alone")

    # ---- 4  the plugin's apply() while a save is queued (Apply pressed straight after "Compute again") -------------
    for label, plan, seps in (("separators added", SORTED, SEPS), ("order only", RESORT, [])):
        m = FakeMO2(os.path.join(T, "f-" + label.replace(" ", "")), MODS)
        log = []
        p = plugin_for(m, log)
        m.refresh(True)                            # compute(): the saving refresh before the pane is read
        m.tick()                                   # Apply is pressed while that refresh's save is still queued
        ok(m.queued, f"apply ({label}): a save is queued when Apply is pressed")
        MM.apply = lambda *a, m=m, plan=plan, seps=seps, **k: (do_apply(m, plan, seps), "backup-folder")[1]
        back = p.apply({"plugins": []}, plugin_moves=False)
        ok(back == "backup-folder" and m.errors == [], f"apply() ({label}): done, MO2 reports nothing", m.errors)
        ok(m.read_file() == plan, f"apply() ({label}): modlist.txt is the plan's, not MO2's older order", m.read_file())
        ok(any("older mod list" in x for x in log), f"apply() ({label}): the put-back is in the log", log)
        m.settle()
        ok(m.read_file() == plan, f"... and it stays the plan's once MO2's later save is written ({label})", m.read_file())

    # ---- 5  nothing queued: no put-back, no extra refresh ------------------------------------------------------------
    m = FakeMO2(os.path.join(T, "g"), MODS)
    log = []
    p = plugin_for(m, log)
    m.settle()
    MM.apply = lambda *a, m=m, **k: (do_apply(m, SORTED, SEPS), "backup-folder")[1]
    m.calls.clear()
    p.apply({"plugins": []}, plugin_moves=False)
    ok(m.calls == [("refresh", False)] and log == [] and m.read_file() == SORTED,
       "apply() with nothing queued: one refresh without saving, nothing logged", (m.calls, log))
finally:
    shutil.rmtree(T, ignore_errors=True)

print("ALL PASS" if not bad else f"{bad} FAILED")
sys.exit(1 if bad else 0)
