"""Rule 66 for the Modlist Manager: the eleven languages load, fall back to English, follow MO2's language, obey
Settings > Language, and the dialog still narrows to 760 px in every one of them (a long German or Russian label that does
not wrap would hold the window wide again - the 1.1.3 complaint).

    python tools\\test_languages.py        exit 0 = every check passed
"""
import importlib.util, os, shutil, sys, tempfile, types
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

os.environ["QT_QPA_PLATFORM"] = "windows" if sys.platform == "win32" else "offscreen"
stub = types.ModuleType("mobase")
stub.__getattr__ = lambda n: type(n, (object,), {"__init__": lambda self, *a, **k: None})
sys.modules["mobase"] = stub
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location("mm", os.path.join(HERE, "MO2ModlistManager.py"))
mm = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mm)
from PyQt6.QtWidgets import QApplication, QWidget

LIMIT = 760
fails = []


def check(ok, what):
    print(("PASS  " if ok else "FAIL  ") + what)
    if not ok:
        fails.append(what)


ENGLISH_APPLY = "Apply"
codes = {"en": "english", "ja": "japanese", "ko": "korean", "zh": "chinese", "ru": "russian", "de": "german",
         "fr": "french", "es": "spanish", "it": "italian", "pl": "polish", "cs": "czech"}

# 1  the loader: each code picks its file, regional codes work, unknown codes fall back to English
for code, name in codes.items():
    got = mm.load_strings(code)
    n = len(mm._STRINGS)
    check(got == name and (n == 0 if name == "english" else n == 118), f"{code}: loads '{got}' ({n} strings)")
    if name != "english":
        check(mm.TR("MM_BtnApply", ENGLISH_APPLY) != ENGLISH_APPLY, f"{code}: Apply is translated -> {mm.TR('MM_BtnApply', ENGLISH_APPLY)}")
for code, name in (("de_DE", "german"), ("zh_CN", "chinese"), ("pt_BR", "english"), ("", "english"), (None, "english"), ("xx", "english")):
    check(mm.load_strings(code) == name, f"code {code!r} -> {name}")
mm.load_strings("de")
check(mm.TR("MM_Copied", "Copied {n} row(s) to the clipboard.", n=7).count("7") == 1, "placeholders are filled in: " + mm.TR("MM_Copied", "x {n}", n=7))
check(mm.TR("MM_NoSuchKey", "English {n}", n=2) == "English 2", "a key a file lacks draws the English written at the call")
check("\n" in mm.TR("MM_RestoreAsk", "x", when="a", kind="b", cur="c", warn=""), "a \\n in a file is a line break")
check(mm.TR("MM_SummaryBpm", " into {n} BPM groups", n=3).startswith(" in 3") or mm.TR("MM_SummaryBpm", "x {n}", n=3).startswith(" "), "a value that starts with a space keeps it")
mm.load_strings("en")

# 2  MO2's language is read from ModOrganizer.ini
root = tempfile.mkdtemp(prefix="mm-lang-")
try:
    ini = os.path.join(root, "ModOrganizer.ini")
    open(ini, "w", encoding="utf-8").write("[General]\nlanguage=ignored\n\n[Settings]\nlanguage=ru_RU\n")
    check(mm.mo2_language(root).startswith("ru") or mm.mo2_language(root) == "ignored", "ModOrganizer.ini language read: " + mm.mo2_language(root))
    open(ini, "w", encoding="utf-8").write("[Settings]\nlanguage=de_DE\n")
    check(mm.mo2_language(root) == "de_DE", "ModOrganizer.ini language=de_DE -> " + mm.mo2_language(root))
    check(mm.mo2_language(os.path.join(root, "nowhere")) == "en", "no ini -> en")

    # 3  the dialog in every language: built, narrow enough, Settings > Language present and saved
    inst = os.path.join(root, "Mo2")
    prof = os.path.join(inst, "profiles", "Test")
    mods = os.path.join(inst, "mods")
    os.makedirs(prof)
    for m in ("SkyUI", "SmoothCam"):
        os.makedirs(os.path.join(mods, m))
        open(os.path.join(mods, m, "meta.ini"), "w").write("[General]\nmodid=0\n")
    open(os.path.join(prof, "modlist.txt"), "w", newline="\r\n").write("# This file was automatically generated by Mod Organizer.\n+SkyUI\n+SmoothCam\n")
    app = QApplication([])
    app.setProperty("dataPath", inst.replace("\\", "/"))
    saved = {}

    class Org:
        def basePath(self): return inst.replace("\\", "/")
        def modsPath(self): return mods.replace("\\", "/")
        def profilePath(self): return prof.replace("\\", "/")
        def profileName(self): return "Test"
        def refresh(self, save=True): pass
        def managedGame(self): raise RuntimeError("no game in the test")
        def pluginSetting(self, plugin, key): return saved.get(key)
        def setPluginSetting(self, plugin, key, value): saved[key] = value

    p = mm.MO2ModlistManager()
    p._organizer = Org()
    p._log = lambda msg: None
    # automatic: follows MO2's language
    open(os.path.join(inst, "ModOrganizer.ini"), "w", encoding="utf-8").write("[Settings]\nlanguage=fr_FR\n")
    p.apply_language()
    check(mm.TR("MM_BtnApply", "Apply") == "Appliquer", "automatic follows MO2 (fr_FR): " + mm.TR("MM_BtnApply", "Apply"))
    saved["language"] = "ja"
    p.apply_language()
    check(mm.TR("MM_BtnApply", "Apply") == "適用", "Settings > Language 'ja' beats MO2's: " + mm.TR("MM_BtnApply", "Apply"))
    saved["language"] = "auto"
    for code in codes:
        saved["language"] = code
        p.apply_language()
        dlg = mm.RulerDialog(p)
        dlg.compute()
        dlg.ensurePolished()
        need = dlg.minimumSizeHint().width()
        check(need <= LIMIT, f"{code}: dialog narrows to {need} px (limit {LIMIT}); tabs: " + ", ".join(dlg.tabs.tabText(i) for i in range(dlg.tabs.count())))
        check(dlg.cb_lang.currentData() == code, f"{code}: Settings > Language shows the saved choice")
        dlg.cb_lang.setCurrentIndex(dlg.cb_lang.findData("pl"))
        check(saved["language"] == "pl", f"{code}: choosing Polski saves 'pl'")
        dlg.close()
finally:
    shutil.rmtree(root, ignore_errors=True)
print("ALL PASS" if not fails else "FAILED: %d" % len(fails))
sys.exit(1 if fails else 0)
